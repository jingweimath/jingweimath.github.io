def main():
    apply = '--apply' in sys.argv

    raw = io.open(SRC, encoding='utf-8', newline='').read()
    d = json.loads(raw)
    qs = d['questions']

    # ---- 前置校验 ----
    err = []
    ids = set(q['id'] for q in qs)
    for k in MAP:
        if k not in ids:
            err.append('MAP 里的 %s 不在文件中' % k)
    missing = [q['id'] for q in qs if not str(q.get('cat', '')).strip()]
    for mid in missing:
        if mid not in MAP:
            err.append('缺标签的 %s 没在 MAP 里' % mid)
    for k in MAP:
        q = next(x for x in qs if x['id'] == k)
        if str(q.get('cat', '')).strip():
            err.append('%s 本来就有 cat=%r，不该被覆盖' % (k, q.get('cat')))
    # cat 必须全部来自本文件已有词表
    known = set(q['cat'] for q in qs if str(q.get('cat', '')).strip())
    for k, (c, t) in MAP.items():
        if c not in known:
            err.append('%s 的 cat=%r 是新词，会与本文件检索分裂' % (k, c))
        if not t.strip():
            err.append('%s 的 topic 为空' % k)
    if err:
        print('[前置校验失败，未做任何改动]')
        for e in err:
            print('  ', e)
        return 1

    print('已有 cat 词表（%d 个）：' % len(known))
    for c in sorted(known):
        print('  ', c)
    print()
    print('待补标签题数：%d，MAP 条目数：%d' % (len(missing), len(MAP)))

    # ---- 统计 ----
    import collections
    before = collections.Counter(q.get('cat', '(空)') for q in qs)
    for k, (c, t) in sorted(MAP.items()):
        q = next(x for x in qs if x['id'] == k)
        q['cat'] = c
        q['topic'] = t
    after = collections.Counter(q.get('cat', '(空)') for q in qs)

    print()
    print('%-16s %6s -> %6s' % ('cat', '补前', '补后'))
    for c in sorted(set(list(before) + list(after))):
        if c == '(空)':
            continue
        if before.get(c, 0) != after.get(c, 0):
            print('%-16s %6d -> %6d' % (c[:16], before.get(c, 0), after.get(c, 0)))
    print('%-16s %6d -> %6d' % ('(空)', before.get('(空)', 0), after.get('(空)', 0)))
    print()
    print('补后仍缺标签的题数：', sum(1 for q in qs
                              if not str(q.get('cat', '')).strip()
                              or not str(q.get('topic', '')).strip()))

    if not apply:
        print()
        print('[DRY-RUN] 未写盘。确认无误后加 --apply')
        return 0

    out = json.dumps(d, ensure_ascii=False, indent=2)
    # 原文件是 CRLF
    out = out.replace('\r\n', '\n').replace('\n', '\r\n')
    with io.open(SRC, 'w', encoding='utf-8', newline='') as f:
        f.write(out)
    print()
    print('[APPLY] 已写盘 ->', SRC)
    return 0


if __name__ == '__main__':
    sys.exit(main())
